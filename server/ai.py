def build_prompt(
    feature: str,
    fact: str,
    question: str,
    rag_excerpts: list[str],
    user_profile: str = "",
    history: list[dict] | None = None,
) -> str:
    """装配通用解读 prompt。

    fact: 功能计算出的确定性盘面文本（卦象/八字/牌阵/黄历字段）。
    rag_excerpts: RAG 检索到的文献摘录，作为唯一解读依据来源。
    """
    rag_block = "\n\n".join(rag_excerpts) if rag_excerpts else "（暂无匹配文献，请依传统通识谨慎解读）"
    guide_block = FEATURE_GUIDES.get(feature, "")
    if guide_block:
        guide_block = "\n\n" + guide_block
    profile_block = f"\n\n【用户画像（个性化参考）】\n{user_profile}" if user_profile else ""
    hist_block = ""
    if history:
        lines = []
        for h in history[-6:]:
            q = h.get("question", "")
            a = (h.get("answer") or "").strip()
            if a:
                # 追问场景：把此前结论的关键要点带上，避免模型改口/自相矛盾。
                # 只取前 400 字，控制 prompt 体积。
                a = a.replace("\n", " ")
                a = a[:400] + ("…" if len(a) > 400 else "")
                lines.append(f"- {h.get('ts','')} 问：{q}\n  此前解读要点：{a}")
            else:
                lines.append(f"- {h.get('ts','')} 问：{q}")
        hist_block = "\n\n【此前对话与提问（保持语境连贯，追问时结论须一致）】\n" + "\n".join(lines)

    return f"""你是一位严谨的中国传统命理学者，正在为用户解读「{feature}」。

【铁律】
1. 你的解读必须严格基于下方【文献依据】与【盘面事实】，引用时注明出处（如"乾卦初九爻辞"「愚者牌正位」）；文献未提及的内容不要编造。若其中某张牌 / 某一项在文献里没有对应条目，直接用该牌（该象）的通行牌义结合牌位正常解读，不要向用户说明"文献未收录""资料缺失"之类的话。
2. 客观平衡、避免"安慰式解读"：短板与长处要各占合理篇幅并给事实依据，不一味说好话，也不渲染夸大负面（各功能的具体落点见下方专属规则）。
3. 语言温和、克制、有分寸：给建设性视角，但"建设性"不等于粉饰；避免绝对化吉凶断语与恐吓式表述。
4. 结合用户的具体问题作答，不要泛泛而谈；结构清晰（可用小标题/分点），篇幅适中。
5. 不要在结尾自行撰写免责声明或"仅供参考"套话——免责说明由系统在正文之后统一附加，你只需输出解读正文。{guide_block}

【用户问题】
{question}
{profile_block}{hist_block}

【盘面事实（确定性计算，不可更改）】
{fact}

【文献依据（RAG 检索，解读须引用于此）】
{rag_block}

现在开始解读："""


async def stream_answer(prompt: str, timeout: float = 300.0):
    """透传流式增量；供各 API 的 StreamingResponse 直接消费。"""
    async for delta in stream_deduce(prompt, timeout=timeout):
        yield delta
